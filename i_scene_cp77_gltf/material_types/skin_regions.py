REGIONS_PER_ATTRIBUTE = 3
REGION_ATTRIBUTE_COUNT = (
    len(DEFAULT_FACE_REGIONS) + REGIONS_PER_ATTRIBUTE - 1
) // REGIONS_PER_ATTRIBUTE
REGION_ATTRIBUTE_PREFIX = "cp77_skin_wrinkle_regions_"


def region_attribute_name(index):
    return f"{REGION_ATTRIBUTE_PREFIX}{int(index):02d}"


def gpu_rect(raw_vector):
    w, x, y, z = raw_vector
    return (w, 1.0 - x, y, 1.0 - z)


def evaluate_region_influences(uv):
    uv = np.asarray(uv, dtype=np.float32).reshape((-1, 2))
    result = np.zeros((len(uv), len(DEFAULT_FACE_REGIONS)), dtype=np.float32)
    if not len(uv):
        return result

    u = uv[:, 0]
    v = uv[:, 1]
    computed = {}
    for region_index, (_name, _is_stretch, parts) in enumerate(DEFAULT_FACE_REGIONS):
        if parts in computed:
            result[:, region_index] = computed[parts]
            continue
        region = np.zeros(len(uv), dtype=np.float32)
        for inner_raw, outer_raw in parts:
            inner = gpu_rect(inner_raw)
            outer = gpu_rect(outer_raw)
            u_weight = np.minimum(
                (u - outer[0]) / (inner[0] - outer[0]),
                (outer[2] - u) / (outer[2] - inner[2]),
            )
            v_weight = np.minimum(
                (v - outer[1]) / (inner[1] - outer[1]),
                (outer[3] - v) / (outer[3] - inner[3]),
            )
            part_weight = np.clip(u_weight, 0.0, 1.0) * np.clip(v_weight, 0.0, 1.0)
            np.maximum(region, part_weight, out=region)
        computed[parts] = region
        result[:, region_index] = region
    return result
