from bpy.props import BoolProperty, EnumProperty, StringProperty
from bpy.types import AddonPreferences

from .addon_identity import ADDON_PACKAGE
from .log import configure_from_preferences
from .registration import RegistrationLedger


def _update_logging_preferences(_self, context):
    configure_from_preferences(context)


class CP77IOSuitePreferences(AddonPreferences):
    bl_idname = ADDON_PACKAGE

    experimental_features: BoolProperty(
        name="Enable Experimental Features",
        description="Experimental Features for Mod Developers, may encounter bugs",
        default=False,
    )

    depotfolder_path: StringProperty(
        name="Depot Path",
        description="Path to your local Depot folder. Used to override the Depot paths contained within json files generated by WolvenKit",
        subtype="DIR_PATH",
        default="",
    )
    game_directory: StringProperty(
        name="Game Directory",
        description="Your Cyberpunk 2077 installation folder",
        subtype="DIR_PATH",
        default="",
    )
    # The sector import dialog's last choices, as its own JSON.
    sector_import_choices: StringProperty(
        options={"HIDDEN"},
        default="",
    )
    # The entity import dialog's last choices, as its own JSON.
    entity_import_choices: StringProperty(
        options={"HIDDEN"},
        default="",
    )
    show_modtools: BoolProperty(
        name="Show Mod Tools",
        description="Show the Mod tools Tab in the 3d viewport",
        default=True,
    )

    context_only: BoolProperty(
        name="Only Show Mod Tools in Context",
        description="Show the Mod tools Tab in the 3d viewport",
        default=False,
    )

    show_meshtools: BoolProperty(
        name="Show the Mesh Tools Panel",
        description="Show the mesh tools panel",
        default=True,
    )

    show_physicstools: BoolProperty(
        name="Show the Physics Tools Panel",
        description="Show the Physics tools panel",
        default=True,
    )

    show_animtools: BoolProperty(
        name="Show the Animation Tools Panel",
        description="Show the anim tools panel",
        default=True,
    )

    log_level: EnumProperty(
        name="Log Level",
        description="Minimum CP77 severity shown in Blender's console; the log file records Debug, or Trace "
        "when this is Debug",
        items=(
            (
                "DEBUG",
                "Debug",
                "Internal decisions, per-resource diagnostics, performance timings, cache activity, warnings, and errors",
            ),
            (
                "INFO",
                "Info",
                "User-visible operation progress and completed results, plus warnings and errors",
            ),
            (
                "WARNING",
                "Warnings",
                "Recoverable degradation, incomplete or ambiguous output requiring attention, plus errors",
            ),
            (
                "ERROR",
                "Errors",
                "Failures that prevent a requested operation or required item from completing",
            ),
        ),
        default="INFO",
        update=_update_logging_preferences,
    )

    log_to_file: BoolProperty(
        name="Write Rotating Log File",
        description="Write the detailed log to the Blender configuration directory",
        default=True,
        update=_update_logging_preferences,
    )

    def draw(self, context):
        layout = self.layout

        box = layout.box()
        box.label(text="Depot Path:")
        row = box.row()
        row.prop(self, "depotfolder_path", text="")
        row = box.row()

        box = layout.box()
        box.label(text="Game Directory:")
        box.prop(self, "game_directory", text="")

        box = layout.box()
        row = box.row()
        row.prop(self, "show_modtools", toggle=1)
        row.prop(self, "experimental_features", toggle=1)

        log_box = layout.box()
        log_box.label(text="Logging")
        log_box.prop(self, "log_level")
        log_box.prop(self, "log_to_file")
        if self.show_modtools:
            row.alignment = "LEFT"
            box = layout.box()
            box.label(text="Mod Tools Preferences")
            split = row.split(factor=0.5, align=True)
            col = split.column(align=True)
            row.alignment = "LEFT"
            row = box.row()
            col = row.column(align=True)
            col.prop(self, "context_only")
            col.prop(self, "show_meshtools")
            col.prop(self, "show_physicstools")
            col.prop(self, "show_animtools")


_LEDGER = RegistrationLedger("preferences")


def register_prefs():
    if not _LEDGER.active:
        _LEDGER.register_classes((CP77IOSuitePreferences,))


def unregister_prefs():
    _LEDGER.cleanup_or_raise()
