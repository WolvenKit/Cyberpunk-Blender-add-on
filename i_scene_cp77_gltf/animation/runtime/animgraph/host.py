from __future__ import annotations

from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from typing import Any, Protocol

from ...model.animgraph.frames import BranchFrame, TrackSnapshot
from ...model.clip.metadata import FPS


@dataclass(frozen=True)
class PreviewSettings:
    """The preview controls a graph compiles and evaluates with"""

    graph_path: str
    visual_tags: str
    component_tags: str
    skeletal_lod: int
    performance_mode: bool


@dataclass(frozen=True)
class SourceClip:
    """An animation clip the host can sample"""

    name: str
    frame_start: float
    frame_end: float
    animation_type: str
    key: int
    handle: Any

    @property
    def duration(self) -> float:
        return (self.frame_end - self.frame_start) / float(FPS)


@dataclass(frozen=True)
class LookAtControls:
    enabled: bool
    part: str
    speed: float


class AnimGraphHost(Protocol):
    """Scene access of an AnimGraph runtime"""

    name: str
    has_graph: bool
    graph_name: str

    @property
    def settings(self) -> PreviewSettings: ...

    # graph
    def nodes_by_handle(self) -> dict[str, Any]: ...
    def graph_variables(self) -> Iterable[Any]: ...
    def float_variable_value(
        self, name: str, rig_inputs: Mapping[str, float] | None
    ) -> float: ...
    def rig_float_value(self, name: str) -> float | None: ...
    def available_animation_names(
        self, source_payload: Mapping[str, Any]
    ) -> frozenset[str]: ...
    def prepare_node_operation(self, node: Any) -> Any: ...
    def prepare_upstream_chain(self, boundary: Any) -> Any: ...
    def refresh_chain(self, plan: Any) -> Any: ...
    def evaluate_chain(self, plan: Any) -> Any: ...
    def apply_chain(self, plan: Any, execution: Any) -> tuple[int, int]: ...

    # bones
    def resolve_bone(self, name: str) -> str | None: ...
    def bone_parent(self, name: str) -> str | None: ...
    def bone_descendants(self, name: str) -> tuple[str, ...]: ...
    def with_ancestor_bones(self, names: Iterable[str]) -> set[str]: ...
    def rig_tags(self) -> tuple[Any, ...]: ...
    def rig_space_contract(self) -> Any: ...
    def rig_part_masks(self) -> Mapping[str, Any]: ...
    def rig_part_rotation_ms(self) -> Mapping[str, Any]: ...
    def source_rig_paths(self) -> tuple[str, ...]: ...
    def source_rig_part_bindings(self) -> tuple[Mapping[str, str], ...]: ...
    def load_rig_datas(self, paths: Iterable[str]) -> tuple[Any, ...]: ...

    # tracks
    def track_names(self) -> tuple[str, ...]: ...
    def has_track(self, name: str) -> bool: ...
    def track_snapshot(self, name: str, source: Any = None) -> TrackSnapshot: ...
    def capture_tracks(self, names: Iterable[str]) -> dict[str, TrackSnapshot]: ...
    def restore_tracks(self, snapshots: Mapping[str, TrackSnapshot]) -> None: ...
    def reference_track_values(self, names: Iterable[str]) -> Mapping[str, float]: ...

    # facial solver
    def bind_facial_graph(self) -> tuple[Any, Any]: ...
    def claim_facial_session(self, session: Any, owner: Any) -> None: ...

    # clips
    def preview_wrapper_variables(self) -> frozenset[str]: ...
    def clip(self, name: str) -> SourceClip | None: ...
    def clip_events(self, clip: SourceClip) -> Any: ...
    def sample_clip(
        self, clip: SourceClip, frame: float
    ) -> tuple[dict[str, dict[str, list[float]]], dict[str, float]]: ...
    def clip_basis(
        self, components: Mapping[str, Any], red_pose_bridge: bool
    ) -> Any: ...
    def additive_storage_mode(self) -> str: ...

    # pose
    def frame_bone_names(self) -> tuple[str, ...]: ...
    def reference_pose_ls(self, names: Iterable[str]) -> Mapping[str, Any]: ...
    def bind_frame_pose(
        self,
        names: tuple[str, ...],
        reference_pose: Mapping[str, Any],
        bind_pose: Mapping[str, Any],
        *,
        count_distinct: bool,
    ) -> int: ...
    def physical_parent_map(self) -> dict[str, str]: ...
    def capture_pose(
        self,
        names: Iterable[str] | None,
        *,
        use_input_basis: bool,
        red_pose_bridge: bool,
    ) -> dict[str, Any]: ...
    def write_pose(
        self, pose: Mapping[str, Any], names: Iterable[str], red_pose_bridge: bool
    ) -> int: ...
    def basis_translations(
        self, pose: Mapping[str, Any], names: Iterable[str], red_pose_bridge: bool
    ) -> list: ...
    def output_basis_changed(self, name: str) -> bool: ...
    def tag_update(self) -> None: ...
    def sync_pose(self) -> None: ...
    def prepare_output_bones(self, names: Iterable[str]) -> None: ...
    def mark_output_bones(self, names: Iterable[str]) -> None: ...

    # physics backends
    def dangle_config_by_handle(self) -> dict[str, int]: ...
    def drag_config_by_handle(self) -> dict[str, int]: ...
    def dangle_frame_requirements(self, config_index: int) -> tuple[str, ...]: ...
    def structured_base_frame_requirements(self) -> tuple[str, ...]: ...
    def step_dangle_node(
        self,
        config_index: int,
        child: BranchFrame,
        raw_dt: float,
        time_dilation: float,
        skip_physics: bool,
    ) -> Any: ...
    def dangle_applied_names(self, step: Any) -> tuple[str, ...]: ...
    def dangle_output_pose(self, step: Any, child: BranchFrame) -> dict[str, Any]: ...
    def drag_runtime_index(self, config_index: int) -> int | None: ...
    def step_drag(
        self, runtime_index: int, raw_dt: float, operation_callback: Callable | None
    ) -> None: ...
    def reset_drag(self, runtime_index: int) -> None: ...

    # preview controls
    def is_playing(self) -> bool: ...
    def consume_external_events(self) -> frozenset[str]: ...
    def preview_features_json(self) -> str: ...
    def preview_vector_input(
        self, group: str, name: str
    ) -> tuple[float, ...] | None: ...
    def look_at_controls(self) -> LookAtControls: ...
    def look_at_target(self) -> tuple[float, float, float]: ...
    def world_vector_to_model(
        self, vector, *, direction: bool
    ) -> tuple[float, float, float]: ...
    def bind_values(self, float_by_handle) -> None: ...
    def frame_change_counters(self) -> tuple[int, int, int]: ...
